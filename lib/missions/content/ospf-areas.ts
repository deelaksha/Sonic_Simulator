/**
 * Missions on the OSPF areas lab (lib/labs/ospf-areas-lab.ts):
 * S1 —area 1 (stub)— S2 (ABR) —area 0— S3 (ABR) —area 2 (NSSA)— S4 (ASBR, EXT 198.51.100.0/24).
 */
import { registerMission } from "../registry";
import { CheckCtx } from "../check";

const hasNeighbor = (c: CheckCtx, sw: string, rid: string) => new RegExp(`^${rid.replace(/\./g, "\\.")}\\s+\\d+\\s+Full/`, "m").test(c.shell(sw, "show ip ospf neighbor"));
const ospfDefault = (c: CheckCtx) => c.route("S1", "0.0.0.0/0")?.type === "ospf";
const area1Stub = (c: CheckCtx, sw: string) => /Area ID: 0\.0\.0\.1 \(Stub\)/.test(c.shell(sw, "show ip ospf"));

registerMission({
  id: "ospf-areas-totally-stubby",
  labId: "ospf-areas",
  kind: "mission",
  level: "intermediate",
  title: "Shrink a stub area's routing table",
  summary:
    "S1 is a small branch switch in stub area 1 with a single exit through S2. It still carries a route for every backbone and NSSA link. Make area 1 totally stubby so S1 keeps only its own networks plus a default route — and H1 must still reach EXT.",
  objectives: [
    {
      id: "inspect",
      title: "On S1, look at the routing table and find the default route a stub area gets",
      hints: ["`exit` sonic-cli, then show ip route", "O>* 0.0.0.0/0 comes from S2: an ABR injects a default summary into a stub area instead of the external routes."],
      check: (c) => c.typed("S1", /show ip route/) && ospfDefault(c),
    },
    {
      id: "abr",
      title: "On S2, confirm it is the ABR for area 1",
      hints: ["show ip ospf on S2 — 'This router is an ABR' and one block per attached area."],
      check: (c) => c.typed("S2", /show ip ospf\s*$/),
    },
    {
      id: "totally-stubby",
      title: "S1 has no inter-area routes left, only the default — with S1–S2 still Full",
      hints: [
        "Inter-area routes are type-3 Summary LSAs generated by the ABR. Only the ABR can stop sending them.",
        "On S2: router ospf → area 1 stub no-summary",
      ],
      check: (c) =>
        ospfDefault(c) && !c.route("S1", "10.0.23.0/30") && !c.route("S1", "10.2.34.0/30") && hasNeighbor(c, "S1", "2.2.2.2"),
    },
    {
      id: "reach",
      title: "H1 still reaches EXT (198.51.100.10)",
      check: (c) => c.ping("H1", "198.51.100.10"),
    },
  ],
  solution: [
    { device: "S1", shell: ["exit", "show ip route"] },
    { device: "S2", shell: ["exit", "show ip ospf"] },
    { device: "S2", klish: ["configure terminal", "router ospf", "area 1 stub no-summary", "end"], waitMs: 3000 },
  ],
  explanation:
    "A stub area blocks type-5 externals and the ABR replaces them with a default type-3 summary (RFC 2328 §3.6), but the other type-3 inter-area summaries still flow in. `area 1 stub no-summary` on the ABR makes the area totally stubby: S2 stops originating type-3 summaries into area 1 except the default, so S1 drops 10.0.23.0/30 and 10.2.34.0/30. S1 has only one exit anyway, so the default route through S2 carries the same traffic with a smaller LSDB and routing table.",
});

registerMission({
  id: "ospf-areas-trouble-stub-flag",
  labId: "ospf-areas",
  kind: "troubleshoot",
  level: "intermediate",
  title: "Branch S1 is cut off after a replacement",
  summary:
    "S1 was replaced with a spare and its configuration rebuilt by hand. Since then H1 cannot reach anything beyond S1. Area 1 is a stub area by design and must stay one — do not change S2.",
  inject(api) {
    api.runCliScript(api.deviceId("S1"), ["configure terminal", "router ospf", "no area 1 stub", "end"]);
  },
  objectives: [
    {
      id: "adjacent",
      title: "S1 and S2 are Full OSPF neighbours",
      hints: [
        "show ip ospf neighbor on S1 and on S2: no neighbour on the S1–S2 link, although the network statements match.",
        "Compare show ip ospf on S1 and S2: how is area 0.0.0.1 labelled on each?",
        "Both ends must agree on the stub flag (E-bit) in their Hellos. On S1: router ospf → area 1 stub",
      ],
      check: (c) => hasNeighbor(c, "S1", "2.2.2.2") && hasNeighbor(c, "S2", "1.1.1.1"),
    },
    {
      id: "default",
      title: "S1 learns its default route from S2",
      check: (c) => ospfDefault(c),
    },
    {
      id: "reach",
      title: "H1 reaches EXT (198.51.100.10)",
      check: (c) => c.ping("H1", "198.51.100.10"),
    },
    {
      id: "still-stub",
      title: "Area 1 is still a stub area on S1 and S2",
      check: (c) => area1Stub(c, "S1") && area1Stub(c, "S2"),
    },
  ],
  solution: [{ device: "S1", klish: ["configure terminal", "router ospf", "area 1 stub", "end"], waitMs: 15000 }],
  explanation:
    "S1 had lost `area 1 stub`, so its Hellos set the E-bit (external routing capable) while S2's, in a stub area, cleared it. RFC 2328 §10.5 requires the E-bit of a received Hello to match the receiving area's configuration, otherwise the Hello is dropped — neither router ever saw the other and the adjacency stayed down without any error on the link. Configuring the area as stub on S1 makes the options match; the adjacency comes up and S2's default summary gives S1 its way out.",
});

registerMission({
  id: "ospf-areas-trouble-area-id",
  labId: "ospf-areas",
  kind: "troubleshoot",
  level: "intermediate",
  title: "The external network is unreachable",
  summary:
    "Since a configuration clean-up on the backbone ABRs, nobody in the network can reach EXT (198.51.100.10) behind S4. S4 belongs to a partner and must not be changed.",
  inject(api) {
    api.runCliScript(api.deviceId("S3"), ["configure terminal", "router ospf", "no network 10.2.34.0/30 area 2", "network 10.2.34.0/30 area 0", "end"]);
  },
  objectives: [
    {
      id: "adjacent",
      title: "S3 and S4 are Full OSPF neighbours",
      hints: [
        "show ip ospf neighbor on S3 and S4: the S3–S4 link has no neighbour.",
        "show ip ospf interface on both ends of the link (S3 Ethernet1, S4 Ethernet0): compare the Area field.",
        "The link belongs in NSSA area 2. On S3: router ospf → no network 10.2.34.0/30 area 0 → network 10.2.34.0/30 area 2",
      ],
      check: (c) => hasNeighbor(c, "S3", "4.4.4.4") && hasNeighbor(c, "S4", "3.3.3.3"),
    },
    {
      id: "external",
      title: "S2 learns the external 198.51.100.0/24 through OSPF",
      check: (c) => c.route("S2", "198.51.100.0/24")?.type === "ospf",
    },
    {
      id: "reach",
      title: "H1 reaches EXT (198.51.100.10)",
      check: (c) => c.ping("H1", "198.51.100.10"),
    },
  ],
  solution: [
    { device: "S3", klish: ["configure terminal", "router ospf", "no network 10.2.34.0/30 area 0", "network 10.2.34.0/30 area 2", "end"], waitMs: 15000 },
  ],
  explanation:
    "S3's network statement put its link to S4 into area 0, while S4 runs it in area 2. Every OSPF packet carries its Area ID, and a router discards packets whose area does not match the receiving interface's area (RFC 2328 §8.2), so no adjacency formed and S4's type-7 external for 198.51.100.0/24 never reached S3 for translation. Moving the network back to area 2 restores the adjacency, S3 translates the type-7 into a type-5 and the rest of the domain learns the external route again.",
});
